-- Step 1b (runs after the PUT of data\*.csv): load the files, then check the row counts.
USE SCHEMA WBR_DB.FINANCE_DEMO;
COPY INTO FINANCE_DIM_PRODUCT FROM @FINANCE_DATA_STAGE/finance_dim_product.csv ON_ERROR = ABORT_STATEMENT;
COPY INTO FINANCE_DIM_SEGMENT FROM @FINANCE_DATA_STAGE/finance_dim_segment.csv ON_ERROR = ABORT_STATEMENT;
COPY INTO FINANCE_FACT_PORTFOLIO_WEEK FROM @FINANCE_DATA_STAGE/finance_fact_portfolio_week.csv ON_ERROR = ABORT_STATEMENT;
COPY INTO FINANCE_FACT_CREDIT_WEEK FROM @FINANCE_DATA_STAGE/finance_fact_credit_week.csv ON_ERROR = ABORT_STATEMENT;
COPY INTO FINANCE_FACT_DEPOSITS_WEEK FROM @FINANCE_DATA_STAGE/finance_fact_deposits_week.csv ON_ERROR = ABORT_STATEMENT;
COPY INTO FINANCE_FACT_ACQUISITION_WEEK FROM @FINANCE_DATA_STAGE/finance_fact_acquisition_week.csv ON_ERROR = ABORT_STATEMENT;

-- expected: 6, 6, 3744, 2496, 1248, 3120
SELECT 'FINANCE_DIM_PRODUCT' AS TABLE_NAME, COUNT(*) AS ROWS_LOADED, 6 AS EXPECTED FROM FINANCE_DIM_PRODUCT
UNION ALL SELECT 'FINANCE_DIM_SEGMENT', COUNT(*), 6 FROM FINANCE_DIM_SEGMENT
UNION ALL SELECT 'FINANCE_FACT_PORTFOLIO_WEEK', COUNT(*), 3744 FROM FINANCE_FACT_PORTFOLIO_WEEK
UNION ALL SELECT 'FINANCE_FACT_CREDIT_WEEK', COUNT(*), 2496 FROM FINANCE_FACT_CREDIT_WEEK
UNION ALL SELECT 'FINANCE_FACT_DEPOSITS_WEEK', COUNT(*), 1248 FROM FINANCE_FACT_DEPOSITS_WEEK
UNION ALL SELECT 'FINANCE_FACT_ACQUISITION_WEEK', COUNT(*), 3120 FROM FINANCE_FACT_ACQUISITION_WEEK;
