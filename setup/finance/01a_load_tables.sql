-- =====================================================================================
-- Keystone Financial (FICTIONAL US consumer bank: credit cards + retail deposits)
-- Step 1: schema, stage and raw tables. Data = the INFERA vertical pack (synthetic, seeded,
-- 104 weeks ending 2026-09-14). The CSV files are uploaded by run_finance_setup.cmd (PUT),
-- then copied in by 01b_copy.sql. Nothing here is real company data.
-- =====================================================================================
USE ROLE WBR_OWNER;
USE WAREHOUSE POWERHOUSE;
CREATE SCHEMA IF NOT EXISTS WBR_DB.FINANCE_DEMO
  COMMENT = 'Keystone Financial: fictional US consumer bank (cards + deposits), synthetic weekly data for demos';
USE SCHEMA WBR_DB.FINANCE_DEMO;

CREATE OR REPLACE FILE FORMAT FINANCE_CSV
  TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 EMPTY_FIELD_AS_NULL = TRUE;
CREATE STAGE IF NOT EXISTS FINANCE_DATA_STAGE FILE_FORMAT = FINANCE_CSV
  COMMENT = 'Keystone Financial (fictional) CSV files';

-- Raw tables keep the pack's names and columns (the ontology document describes them).
-- Their dates are frozen; the SV_SRC_* views in step 2 roll them forward to the last full week.
CREATE OR REPLACE TABLE FINANCE_DIM_PRODUCT (
  PRODUCT_ID VARCHAR, PRODUCT_NAME VARCHAR, PRODUCT_TYPE VARCHAR, TIER VARCHAR,
  PORTFOLIO_MIX_PCT NUMBER(9,3), AVG_APR_PCT NUMBER(9,3));
CREATE OR REPLACE TABLE FINANCE_DIM_SEGMENT (
  SEGMENT_ID VARCHAR, SEGMENT_NAME VARCHAR, AVG_FICO NUMBER(5,0), PORTFOLIO_MIX_PCT NUMBER(9,3), DESCRIPTION VARCHAR);
CREATE OR REPLACE TABLE FINANCE_FACT_PORTFOLIO_WEEK (
  WEEK_START_DATE DATE, FISCAL_YEAR NUMBER(4,0), FISCAL_WEEK NUMBER(2,0), PRODUCT_ID VARCHAR, SEGMENT_ID VARCHAR,
  ENDING_BALANCE NUMBER(18,2), NEW_ACCOUNTS NUMBER(12,0), CLOSED_ACCOUNTS NUMBER(12,0), ACTIVE_ACCOUNTS NUMBER(12,0),
  PURCHASE_VOLUME NUMBER(18,2), INTERCHANGE_REVENUE NUMBER(18,2), REWARDS_EXPENSE NUMBER(18,2),
  NET_INTEREST_INCOME NUMBER(18,2), COST_OF_FUNDS_DOLLARS NUMBER(18,2), REVOLVE_RATE_PCT NUMBER(9,3), APR_PCT NUMBER(9,3));
CREATE OR REPLACE TABLE FINANCE_FACT_CREDIT_WEEK (
  WEEK_START_DATE DATE, PRODUCT_ID VARCHAR, SEGMENT_ID VARCHAR,
  DPD_30_BALANCE NUMBER(18,2), DPD_60_BALANCE NUMBER(18,2), DPD_90_BALANCE NUMBER(18,2),
  GROSS_CHARGEOFF_DOLLARS NUMBER(18,2), RECOVERY_DOLLARS NUMBER(18,2), NET_CHARGEOFF_DOLLARS NUMBER(18,2),
  DELINQUENCY_RATE_PCT NUMBER(9,3), ANNUALIZED_LOSS_RATE_PCT NUMBER(9,3), AVG_FICO NUMBER(5,0));
CREATE OR REPLACE TABLE FINANCE_FACT_DEPOSITS_WEEK (
  WEEK_START_DATE DATE, PRODUCT_ID VARCHAR, SEGMENT_ID VARCHAR,
  DEPOSIT_BALANCE NUMBER(18,2), RUNOFF_DOLLARS NUMBER(18,2), MATURING_DOLLARS NUMBER(18,2), NEW_MONEY_DOLLARS NUMBER(18,2),
  RATE_PAID_PCT NUMBER(9,3), COMPETITOR_RATE_PCT NUMBER(9,3), RATE_GAP_PCT NUMBER(9,3));
CREATE OR REPLACE TABLE FINANCE_FACT_ACQUISITION_WEEK (
  WEEK_START_DATE DATE, PRODUCT_ID VARCHAR, CHANNEL VARCHAR,
  MARKETING_SPEND NUMBER(18,2), APPLICATIONS NUMBER(12,0), APPROVALS NUMBER(12,0), BOOKINGS NUMBER(12,0),
  COST_PER_BOOKING NUMBER(12,2), AVG_INITIAL_CREDIT_LINE NUMBER(12,2));
